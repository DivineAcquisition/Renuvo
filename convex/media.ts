/**
 * The worker behind Creative Studio's generation jobs. Internal only.
 *
 *  - A job is claimed once (queued → running). A second schedule of the same job does nothing.
 *  - An image request is one call. If its answer is lost, the job is "uncertain": the provider may have
 *    made and billed the image, so it counts against the allowance and is never sent again on its own.
 *  - A video is one interaction whose id is saved first; after that the job is only polled, so a
 *    restart, a repeated poll or a refresh never starts a second generation.
 *  - Outputs are copied into Selestial's storage straight away, before any provider link could expire.
 *  - Stopping a video stops Selestial waiting for it; the provider may still finish and bill, and the job
 *    says so.
 */
import { v } from "convex/values";

import { internal } from "./_generated/api";
import type { Doc, Id } from "./_generated/dataModel";
import { internalAction, internalMutation, internalQuery, type ActionCtx } from "./_generated/server";
import { AiError, aiError } from "./lib/ai/errors";
import { interactionId, interactionState, interactionVideo, readVideo, startVideo, type Interaction } from "./lib/ai/google";
import { editImage, generateImage, type ImageSize } from "./lib/ai/openai";
import { REGISTRY, type Capability } from "./lib/ai/registry";
import { recordUsage, settle } from "./lib/ai/usage";
import { finishExecution } from "./lib/billing/executions";
import { reserveExecution } from "./lib/billing/reserve";
import type { GenerationParams } from "./lib/ai/media";
import { recordEvent } from "./lib/events";

const POLL_MS = 15_000;
/** How long a video may take before Selestial stops waiting and reports it. */
const VIDEO_PATIENCE_MS = 30 * 60_000;
/** A running job whose worker said nothing for this long is picked up again by the sweep. */
const STALE_MS = 10 * 60_000;

const PROVENANCE: Record<string, string> = {
  openai: "Generated by OpenAI. Any C2PA provenance the provider adds is kept in the file.",
  google: "Generated by Google Gemini. Google adds an invisible SynthID watermark.",
};

export const claim = internalMutation({
  args: { jobId: v.id("mediaJobs") },
  handler: async (ctx, args) => {
    const job = await ctx.db.get(args.jobId);
    if (!job) return null;
    if (job.state === "cancel_requested" && !job.providerRef) {
      // Stopped before anything reached the provider: nothing was billed.
      await ctx.db.patch(job._id, { state: "cancelled", finishedAt: Date.now(), error: "Stopped before it started. Nothing was sent to the provider." });
      await settle(ctx, job, { images: 0, videos: 0 });
      if (job.executionId) await finishExecution(ctx, job.executionId, { ended: "canceled" });
      return null;
    }
    if (job.state !== "queued") return null;
    await ctx.db.patch(job._id, { state: "running", attempts: job.attempts + 1, heartbeatAt: Date.now() });
    const company = await ctx.db.get(job.companyId);
    const sources = [];
    for (const sourceId of job.sources) {
      const asset = await ctx.db.get(sourceId);
      if (asset && asset.companyId === job.companyId) sources.push({ storageId: asset.storageId, contentType: asset.contentType, label: asset.label });
    }
    return { job: { ...job, state: "running" as const }, sources, companyKnown: Boolean(company) };
  },
});

export const current = internalQuery({
  args: { jobId: v.id("mediaJobs") },
  handler: async (ctx, args) => ctx.db.get(args.jobId),
});

/** Saves the provider's id for this job before anything waits on it. */
export const remember = internalMutation({
  args: { jobId: v.id("mediaJobs"), providerRef: v.string() },
  handler: async (ctx, args) => {
    const job = await ctx.db.get(args.jobId);
    if (!job || job.providerRef) return null;
    await ctx.db.patch(job._id, { providerRef: args.providerRef, heartbeatAt: Date.now() });
    return null;
  },
});

const usageFor = (job: Doc<"mediaJobs">) => REGISTRY[job.capability as Capability].primary;

/** Stores the outputs as generated assets and closes the job. Repeated calls change nothing. */
export const complete = internalMutation({
  args: { jobId: v.id("mediaJobs"), outputs: v.array(v.object({ storageId: v.id("_storage"), contentType: v.string(), size: v.number() })), revisedPrompt: v.optional(v.string()), raw: v.optional(v.string()) },
  handler: async (ctx, args) => {
    const job = await ctx.db.get(args.jobId);
    if (!job || job.state === "completed" || job.state === "failed" || job.state === "cancelled") {
      // A late or repeated answer: its files are not wanted.
      for (const output of args.outputs) await ctx.storage.delete(output.storageId);
      return null;
    }
    const params = JSON.parse(job.params) as GenerationParams;
    const assets: Id<"mediaAssets">[] = [];
    for (const [index, output] of args.outputs.entries()) {
      assets.push(
        await ctx.db.insert("mediaAssets", {
          companyId: job.companyId,
          kind: output.contentType.startsWith("video/") ? "video" : "image",
          origin: "generated",
          storageId: output.storageId,
          contentType: output.contentType,
          size: output.size,
          label: `${job.kind === "video_generate" ? "Generated video" : job.kind === "image_edit" ? "Edited image" : "Generated image"}${args.outputs.length > 1 ? ` ${index + 1}` : ""}`,
          sources: job.sources.length ? job.sources : undefined,
          generation: { jobId: job._id, provider: job.provider, model: job.model, prompt: job.prompt, revisedPrompt: args.revisedPrompt, provenance: PROVENANCE[job.provider] ?? "Generated by an AI model." },
          createdBy: job.requestedBy,
          createdAt: Date.now(),
        }),
      );
    }
    const stopped = job.state === "cancel_requested";
    await ctx.db.patch(job._id, { state: "completed", outputs: assets, finishedAt: Date.now(), error: stopped ? "You asked to stop, but the provider had already finished. The result is kept and counts against the allowance." : undefined });
    const used = job.kind === "video_generate" ? { images: 0, videos: 1 } : { images: args.outputs.length, videos: 0 };
    await settle(ctx, job, used);
    // Charged per image or video delivered; the rest of the hold goes back.
    if (job.executionId) await finishExecution(ctx, job.executionId, { completedUnits: used.images + used.videos });
    await recordUsage(ctx, { companyId: job.companyId, memberId: job.requestedBy, feature: job.kind, capability: job.capability as Capability, model: usageFor(job), jobId: job._id, units: job.kind === "video_generate" ? { videoSeconds: params.durationSeconds } : { images: args.outputs.length }, raw: args.raw ? JSON.parse(args.raw) : undefined, outcome: "ok" });
    await recordEvent(ctx, { companyId: job.companyId, type: "media_job.completed", actor: { kind: "system" }, subject: { table: "mediaJobs", id: job._id }, data: { outputs: assets.length } });
    return null;
  },
});

/**
 * Closes a job that did not produce anything. `billed` is whether the provider may have charged: an
 * uncertain answer or a video that was already running counts as used.
 */
export const fail = internalMutation({
  args: { jobId: v.id("mediaJobs"), state: v.union(v.literal("failed"), v.literal("uncertain"), v.literal("cancelled")), kind: v.string(), words: v.string(), billed: v.boolean() },
  handler: async (ctx, args) => {
    const job = await ctx.db.get(args.jobId);
    if (!job || job.state === "completed" || job.state === "failed" || job.state === "cancelled" || job.state === "uncertain") return null;
    await ctx.db.patch(job._id, { state: args.state, error: args.words, errorKind: args.kind, finishedAt: Date.now() });
    await settle(ctx, job, args.billed ? job.reserved : { images: 0, videos: 0 });
    // Nothing was delivered, so the customer is not charged, even when the provider may have billed Selestial.
    if (job.executionId) await finishExecution(ctx, job.executionId, { ended: args.state === "cancelled" ? "canceled" : "failed" });
    await recordUsage(ctx, { companyId: job.companyId, memberId: job.requestedBy, feature: job.kind, capability: job.capability as Capability, model: usageFor(job), jobId: job._id, units: {}, outcome: args.state === "uncertain" ? "uncertain" : "error", errorKind: args.kind });
    await recordEvent(ctx, { companyId: job.companyId, type: `media_job.${args.state}`, actor: { kind: "system" }, subject: { table: "mediaJobs", id: job._id }, data: { kind: args.kind } });
    return null;
  },
});

export const touch = internalMutation({
  args: { jobId: v.id("mediaJobs") },
  handler: async (ctx, args) => {
    const job = await ctx.db.get(args.jobId);
    if (job && (job.state === "running" || job.state === "cancel_requested")) await ctx.db.patch(job._id, { heartbeatAt: Date.now() });
    return job ? { state: job.state, cancelRequested: job.cancelRequestedAt !== undefined, createdAt: job.createdAt } : null;
  },
});

async function storeBytes(ctx: { storage: { store: (blob: Blob) => Promise<Id<"_storage">> } }, bytes: Uint8Array, contentType: string) {
  const storageId = await ctx.storage.store(new Blob([bytes.slice().buffer], { type: contentType }));
  return { storageId, contentType, size: bytes.length };
}

const failWords = (error: unknown) => (error instanceof AiError ? { kind: error.kind, words: error.words } : { kind: "outage", words: "The generation failed inside Selestial." });

export const run = internalAction({
  args: { jobId: v.id("mediaJobs") },
  handler: async (ctx, args): Promise<null> => {
    const claimed = await ctx.runMutation(internal.media.claim, { jobId: args.jobId });
    if (!claimed) return null;
    const { job, sources } = claimed;
    // Credits are held before the provider is called. Without a verified hold, nothing is generated.
    const held = job.executionId ? await reserveExecution(ctx, job.executionId) : { ok: false as const, message: "This generation has no credit hold, so it was not started. Nothing was charged." };
    if (!held.ok) {
      await ctx.runMutation(internal.media.fail, { jobId: job._id, state: "failed", kind: "billing", words: held.message, billed: false });
      return null;
    }
    const params = JSON.parse(job.params) as GenerationParams;
    const model = { ...REGISTRY[job.capability as Capability].primary, model: job.model };
    try {
      if (job.kind === "video_generate") {
        const image = sources[0] ? await ctx.storage.get(sources[0].storageId) : null;
        const interaction = await startVideo(model, { prompt: job.prompt, aspectRatio: params.aspectRatio ?? "16:9", durationSeconds: params.durationSeconds ?? 6, image: image ? { bytes: new Uint8Array(await image.arrayBuffer()), mimeType: sources[0].contentType } : undefined });
        await finishVideo(ctx, job._id, interaction);
        return null;
      }
      const result =
        job.kind === "image_edit"
          ? await editImage(model, {
              prompt: job.prompt,
              size: (params.size ?? "1024x1024") as ImageSize,
              images: await Promise.all(sources.map(async (source, index) => ({ bytes: new Uint8Array(await (await ctx.storage.get(source.storageId))!.arrayBuffer()), mimeType: source.contentType, name: `source-${index + 1}.${source.contentType.split("/")[1] ?? "png"}` }))),
              safetyIdentifier: job.companyId,
            })
          : await generateImage(model, { prompt: job.prompt, size: (params.size ?? "1024x1024") as ImageSize, quality: params.quality, n: params.n, safetyIdentifier: job.companyId });
      const outputs = [];
      for (const image of result.images) outputs.push(await storeBytes(ctx, image.bytes, image.mimeType));
      await ctx.runMutation(internal.media.complete, { jobId: job._id, outputs, revisedPrompt: result.revisedPrompt ?? undefined, raw: result.usage ? JSON.stringify(result.usage) : undefined });
    } catch (error) {
      const { kind, words } = failWords(error);
      await ctx.runMutation(internal.media.fail, { jobId: job._id, state: kind === "uncertain" ? "uncertain" : "failed", kind, words, billed: kind === "uncertain" });
    }
    return null;
  },
});

/** Takes a video interaction as far as it has got: stored, failed, or polled again later. */
async function finishVideo(ctx: ActionCtx, jobId: Id<"mediaJobs">, interaction: Interaction) {
  const id = interactionId(interaction);
  if (id) await ctx.runMutation(internal.media.remember, { jobId, providerRef: id });
  const state = interactionState(interaction);
  if (state === "completed") {
    const video = interactionVideo(interaction);
    if (!video) throw aiError("invalid_output", "The provider said the video was ready but sent no video.");
    await ctx.runMutation(internal.media.complete, { jobId, outputs: [await storeBytes(ctx, video.bytes, video.mimeType)], raw: interaction.usage ? JSON.stringify(interaction.usage) : undefined });
    return;
  }
  if (state === "failed") {
    // The provider reported a failure; it bills completed generations.
    await ctx.runMutation(internal.media.fail, { jobId, state: "failed", kind: "rejected_input", words: interaction.error?.message ? "The provider could not make this video. Try a different prompt." : "The provider could not make this video.", billed: false });
    return;
  }
  if (!id) throw aiError("uncertain", "The provider started the video but returned no reference to follow it.");
  await ctx.scheduler.runAfter(POLL_MS, internal.media.poll, { jobId });
}

/** Follows a video already started. Repeating it changes nothing; it never starts a new one. */
export const poll = internalAction({
  args: { jobId: v.id("mediaJobs") },
  handler: async (ctx, args): Promise<null> => {
    const state = await ctx.runMutation(internal.media.touch, { jobId: args.jobId });
    if (!state || (state.state !== "running" && state.state !== "cancel_requested")) return null;
    const job = await ctx.runQuery(internal.media.current, { jobId: args.jobId });
    if (!job?.providerRef) return null;
    if (state.cancelRequested) {
      await ctx.runMutation(internal.media.fail, { jobId: job._id, state: "cancelled", kind: "cancelled", words: "Stopped. Selestial no longer waits for this video, but the provider may still have finished and billed it, so it counts against the allowance.", billed: true });
      return null;
    }
    if (Date.now() - state.createdAt > VIDEO_PATIENCE_MS) {
      await ctx.runMutation(internal.media.fail, { jobId: job._id, state: "uncertain", kind: "timeout", words: "The provider has not finished this video after 30 minutes. It was not started again.", billed: true });
      return null;
    }
    try {
      await finishVideo(ctx, job._id, await readVideo(job.providerRef));
    } catch (error) {
      const { kind, words } = failWords(error);
      // A failed poll is not a failed video: try again later, within the patience window.
      if (kind === "outage" || kind === "rate_limited" || kind === "timeout") await ctx.scheduler.runAfter(POLL_MS * 2, internal.media.poll, { jobId: job._id });
      else await ctx.runMutation(internal.media.fail, { jobId: job._id, state: "uncertain", kind, words, billed: true });
    }
    return null;
  },
});

/** Jobs whose worker stopped reporting: a video with a reference is followed again; anything else is reported, never resent. */
export const sweep = internalMutation({
  args: {},
  handler: async (ctx) => {
    const cutoff = Date.now() - STALE_MS;
    for (const state of ["running", "cancel_requested"] as const) {
      const stale = await ctx.db
        .query("mediaJobs")
        .withIndex("by_state_heartbeat", (q) => q.eq("state", state).lt("heartbeatAt", cutoff))
        .take(50);
      for (const job of stale) {
        if (job.kind === "video_generate" && job.providerRef) {
          await ctx.db.patch(job._id, { heartbeatAt: Date.now() });
          await ctx.scheduler.runAfter(0, internal.media.poll, { jobId: job._id });
        } else {
          await ctx.db.patch(job._id, { state: "uncertain", error: "The worker stopped before the provider answered. The request may have run, so it was not sent again.", errorKind: "uncertain", finishedAt: Date.now() });
          await settle(ctx, job, job.reserved);
          if (job.executionId) await finishExecution(ctx, job.executionId, { ended: "failed" });
        }
      }
    }
    return null;
  },
});
